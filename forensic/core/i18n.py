MISSING = object()


def t(key: str, **kwargs: object) -> str:
    """Translate ``key``; unknown keys fall back to English then to the key.

    The language comes from :func:`set_lang` and nothing else.  This used to
    take a ``lang`` argument, and because ``**kwargs`` is what the wrappers
    forward, a parameter called ``lang`` here meant a caller passing
    ``ctx.t("x", lang="pl")`` would have set the *language* instead of formatting
    the string — a silent wrong answer rather than a type error.
    """
    active = STATE["lang"]
    table = STRINGS.get(active, STRINGS[DEFAULT_LANG])
    value = table.get(key, MISSING)
    if value is MISSING:
        value = STRINGS["en"].get(key, MISSING)
    if value is MISSING:
        return key
    if kwargs:
        return str(value).format(**kwargs)
    return str(value)


def set_lang(lang: str) -> None:
    if lang in LANGUAGES:
        STATE["lang"] = lang
        os.environ["FORENSIC_LANG"] = lang


def get_lang() -> str:
    return STATE.get("lang", DEFAULT_LANG)


def set_reveal(value: bool) -> None:
    STATE["reveal"] = "true" if value else "false"


def reveal() -> bool:
    return STATE.get("reveal", "false") == "true"
